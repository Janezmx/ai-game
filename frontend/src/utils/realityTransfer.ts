/**
 * 按关卡取本关现实迁移文案。
 * level 越界（0 / 6 / undefined / NaN）时钳位到 1-5 并回退第 1 关，不抛异常——
 * 旧存档可能缺 level 字段，展示层不能因此白屏。
 */
export function getRealityTransfer(level: number): RealityTransferCopy {
  const safe = Math.min(5, Math.max(1, Math.floor(Number(level) || 1)));
  return REALITY_BY_LEVEL[safe] || REALITY_BY_LEVEL[1];
}

